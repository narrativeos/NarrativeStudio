    fn the_term_tables_do_not_overlap_each_other() {
        // A word in two tables would take whichever precision the caller happens to look
        // at first, which is a coin toss rather than a reading.
        let mut seen: Vec<&str> = Vec::new();
        for table in [SOLAR_TERMS, FESTIVALS, HOUR_PERIODS, WEEKDAYS] {
            for word in table {
                assert!(!seen.contains(word), "{word} is in two term tables");
                seen.push(word);
            }
        }
        assert_eq!(SOLAR_TERMS.len(), 24, "the year has 24 solar terms");
    }

    #[test]
    fn an_era_name_that_is_also_a_festival_is_told_apart_by_the_number() {
        // 上元 is a festival and the era name of two Tang emperors, a Nanzhao king, and a
        // rebel a thousand years apart. The regnal number separates them when it can.
        assert_eq!(era_candidates("上元", 2), vec![675, 761, 785]);
        assert_eq!(era_candidates("上元", 8), vec![791]);
        assert!(FESTIVALS.contains(&"上元"));
    }
