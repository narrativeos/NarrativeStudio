/// The Gregorian year a regnal year falls in, e.g. 乾隆 + 3 → 1738.
pub fn era_year(start: i32, end: i32, regnal: u32) -> Option<i32> {
    if regnal == 0 {
        return None;
    }
    let year = start + regnal as i32 - 1;
    (year <= end).then_some(year)
}

/// Every era in the table whose name matches and whose regnal year is possible.
///
/// Names are shared — 至元 names both a 1264 and a 1335 accession, 建兴 a Shu-Han and a
/// Jin reign, 永嘉 a 145 and a 307 — and the regnal number usually rules one of them out
/// by being impossible for it. When two remain, the caller is told there are two answers
/// rather than being handed whichever came first in the table.
pub fn era_candidates(name: &str, regnal: u32) -> Vec<i32> {
    let mut years: Vec<i32> = ERAS
        .iter()
        .filter(|(era, _, _)| *era == name)
        .filter_map(|(_, start, end)| era_year(*start, *end, regnal))
        .collect();
    // One reign is often dated in more than one regime's table (长兴 ends in 933 in 后唐,
    // in 934 in 吴越, in 932 in 荆南). Three spans, one year: that is one answer, and it
    // must not come back wearing an ambiguity flag.
    years.sort_unstable();
    years.dedup();
    years
}

/// The value of a single CJK or ASCII digit glyph.
fn digit_glyph(c: char) -> Option<u32> {
    match c {
        '0'..='9' => Some(c as u32 - '0' as u32),
        '〇' | '零' => Some(0),
        '一' => Some(1),
        '二' => Some(2),
        '三' => Some(3),
        '四' => Some(4),
        '五' => Some(5),
        '六' => Some(6),
        '七' => Some(7),
        '八' => Some(8),
        '九' => Some(9),
        _ => None,
    }
}

/// A count up to 99, ASCII or written out (`三`, `十`, `十二`, `二十五`).
pub fn small_count(chars: &[char], at: usize) -> Option<(u32, usize)> {
    if chars.get(at).is_some_and(|c| c.is_ascii_digit()) {
        let mut number = String::new();
        let mut i = at;
        while i < chars.len() && chars[i].is_ascii_digit() {
            number.push(chars[i]);
            i += 1;
        }
        return number.parse::<u32>().ok().map(|n| (n, i));
    }
    if chars.get(at) == Some(&'十') {
        let tail = chars
            .get(at + 1)
            .and_then(|c| digit_glyph(*c))
            .filter(|v| *v > 0)
            .unwrap_or(0);
        return Some((10 + tail, at + 1 + usize::from(tail > 0)));
    }
    let leading = digit_glyph(*chars.get(at)?)?;
    if leading == 0 {
        return None;
    }
    if chars.get(at + 1) == Some(&'十') {
        let tail = chars
            .get(at + 2)
            .and_then(|c| digit_glyph(*c))
            .filter(|v| *v > 0)
            .unwrap_or(0);
        return Some((leading * 10 + tail, at + 2 + usize::from(tail > 0)));
    }
    Some((leading, at + 1))
}

/// The lunar month spelled out as a name rather than a number: 正月, 冬月, 腊月, and a
/// leap month written 闰X月. Returns (month, is_leap, end offset).
///
/// A plain `三月` is deliberately absent: it is a month the solar matcher already reads,
/// and calling it lunar would be a guess about which calendar the writer meant.
pub fn lunar_month_name(chars: &[char], at: usize) -> Option<(u32, bool, usize)> {
    let leap = chars.get(at) == Some(&'闰');
    let head = if leap { at + 1 } else { at };
    let named = match chars.get(head) {
        Some('正') => Some((1, 1)),
        Some('冬') => Some((11, 1)),
        Some('腊') => Some((12, 1)),
        _ => None,
    };
    if let Some((month, len)) = named {
        return (chars.get(head + len) == Some(&'月')).then_some((month, leap, head + len + 1));
    }
    if !leap {
        return None;
    }
    // 闰X月: the number is there; the leap prefix is what makes it lunar.
    let (month, after) = small_count(chars, head)?;
    if (1..=12).contains(&month) && chars.get(after) == Some(&'月') {
        return Some((month, true, after + 1));
    }
    None
}

/// A lunar day name: 初八, 初十, 二十, 廿三, 三十, and the bare 十五 that 八月十五 and
/// 正月十五 are made of. Returns (day, end offset).
pub fn lunar_day_name(chars: &[char], at: usize) -> Option<(u32, usize)> {
    if chars.get(at) == Some(&'初') {
        let (day, after) = small_count(chars, at + 1)?;
        if (1..=9).contains(&day) {
            return Some((day, after));
        }
        return (day == 10).then_some((10, after));
    }
    if chars.get(at) == Some(&'廿') {
        return match small_count(chars, at + 1) {
            Some((day, after)) if (1..=9).contains(&day) => Some((20 + day, after)),
            _ => (chars.get(at + 1) == Some(&'十')).then_some((20, at + 2)),
        };
    }
    if chars.get(at) == Some(&'十') && chars.get(at + 1) == Some(&'五') {
        return Some((15, at + 2));
    }
    if chars.get(at) == Some(&'三') && chars.get(at + 1) == Some(&'十') {
        return Some((30, at + 2));
    }
    None
}

/// A lunar date to a Gregorian one, through the astronomical engine.
///
/// `None` means the date is refused: the month does not exist that year, the month was
/// shorter than the day, or the year is outside what the engine models. Refusal is the
/// point — 乾隆三年十二月三十 may be a date a novel wrote, and no calendar in 1738 held it.
pub fn lunar_to_solar_date(year: i32, month: u32, day: u32, leap: bool) -> Option<NaiveDate> {
    // A leap month that year never had is one the engine does not refuse: asked for 闰十月
    // in 2023 it quietly answers with the ordinary 十月. Checked here instead, because a
    // leap month is exactly the case where the text is asking for something specific.
    if leap && lunar_lite::leap_month(year).ok().flatten() != Some(u8::try_from(month).ok()?) {
        return None;
    }
    let solar = lunar_to_solar(LunarDate {
        year,
        month: u8::try_from(month).ok()?,
        day: u8::try_from(day).ok()?,
        is_leap_month: leap,
    })
    .ok()?;
    NaiveDate::from_ymd_opt(solar.year, u32::from(solar.month), u32::from(solar.day))
}

