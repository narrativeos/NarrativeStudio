//! 历法: the calendar facts the time line leans on.
//!
//! Three kinds of thing live here, and they are not equally solid:
//!
//! - **Arithmetic** — the sexagenary cycle (干支). A 60-year wheel with no data behind
//!   it: `(year - 4) mod 60` places a year in the wheel, and that is all it places.
//! - **Conversion** — lunar months against the Gregorian calendar, and the 干支 of a
//!   lunar year. This is delegated to `lunar-lite` (MIT), whose kernel is adapted from
//!   `6tail/tyme4rs`: new-moon and solar-term astronomy rather than a hard-coded table,
//!   so it reaches 1738 as easily as 2024. It answers `Err` rather than guessing when a
//!   date is out of range or a month has too few days, which is the behaviour we want.
//! - **History** — which reign era (年号) ran in which years. There is no library for this;
//!   it is a table, transcribed from the publicly maintained 中国年号列表 (CC BY-SA 4.0),
//!   which follows 李崇智《中国历代年号考》, and it keeps that license — the attribution and
//!   ShareAlike notice is in the repo's `NOTICE`. Every era the source dates, 新莽 to 民国,
//!   including the short-lived ones a chronicle records and a novel rarely names.
//!
//! What this module deliberately does not do is invent a year. An era name whose regnal
//! number does not fit its span is refused; a 干支 year is a wheel position, and a wheel
//! position is not a year — the caller has to anchor it against dates the document itself
//! already gives.
//!
//! Boundaries are approximate in one direction that cannot be removed: an era was
//! proclaimed in the middle of a year, so 「乾隆元年」 covers part of 1736 and part of the
//! lunar year before it. Everything here resolves to a Gregorian *year*, and the time
//! line says so.

use chrono::NaiveDate;
use lunar_lite::{lunar_to_solar, LunarDate};

/// The ten Heavenly Stems, in order.
pub const STEMS: [char; 10] = ['甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸'];

/// The twelve Earthly Branches, in order.
pub const BRANCHES: [char; 12] = [
    '子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥',
];

/// The wheel position of a Gregorian year: 4 CE is 甲子.
pub fn ganzhi_index_of_year(year: i32) -> usize {
    (i64::from(year) - 4).rem_euclid(60) as usize
}

/// The wheel position of a two-character 干支, refusing anything off the wheel:
/// `甲子` is a position, `甲丑` is not (the cycle only pairs stems and branches of the
/// same parity), and a made-up pair must not become a year.
pub fn ganzhi_index(text: &str) -> Option<usize> {
    let chars: Vec<char> = text.chars().collect();
    if chars.len() != 2 {
        return None;
    }
    let stem = STEMS.iter().position(|c| *c == chars[0])?;
    let branch = BRANCHES.iter().position(|c| *c == chars[1])?;
    // Walk the wheel rather than solving for it: 60 steps is nothing, and it cannot
    // produce an index that the cycle never visits.
    (0..60).find(|i| i % 10 == stem && i % 12 == branch)
}

/// Every Gregorian year in `[lo, hi]` sitting at this wheel position.
pub fn ganzhi_years(index: usize, lo: i32, hi: i32) -> Vec<i32> {
    let mut out = Vec::new();
    if lo > hi {
        return out;
    }
    // The first position on or after `lo`, then every 60 years from there.
    let offset = (ganzhi_index_of_year(lo) as i64 - index as i64).rem_euclid(60);
    let mut year = lo + (60 - offset as i32) % 60;
    while year <= hi {
        out.push(year);
        year += 60;
    }
    out
}

